var (
	iconMu    sync.Mutex
	iconCache = map[string]*ui.SVG{}
)

// glyph returns one of the interface's icons.
func glyph(name string) *ui.SVG {
	return cachedSVG("glyph:"+name, func() []byte { return []byte(glyphSources[name]) })
}

// programIcon returns a program's icon from the program table, or nil.
func programIcon(name string) *ui.SVG {
	if name == "" {
		return nil
	}
	return cachedSVG("program:"+name, func() []byte { return programs.IconSVG(name) })
}

func cachedSVG(key string, load func() []byte) *ui.SVG {
	iconMu.Lock()
	defer iconMu.Unlock()
	if s, ok := iconCache[key]; ok {
		return s
	}
	var s *ui.SVG
	if data := load(); len(data) > 0 {
		if parsed, err := ui.ParseSVG(data); err == nil {
			s = parsed
		}
	}
	iconCache[key] = s
	return s
}
